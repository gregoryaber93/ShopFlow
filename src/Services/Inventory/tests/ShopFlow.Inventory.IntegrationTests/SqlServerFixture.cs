using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using ShopFlow.Inventory.Application;
using ShopFlow.Inventory.Infrastructure;
using ShopFlow.Inventory.Infrastructure.Persistence;
using ShopFlow.Messaging.Outbox;
using Testcontainers.MsSql;

namespace ShopFlow.Inventory.IntegrationTests;

/// <summary>
/// SQL Server in a Docker container with the database migrated by the same EF Core migrations that go to Azure SQL.
/// </summary>
/// <remarks>
/// Skipped by default; run in CI with the <c>SHOPFLOW_RUN_INTEGRATION_TESTS=1</c> variable.
/// AZURE: the container uses SQL authentication (the sa login with a password generated by Testcontainers).
/// This is the only place in the repository with a SQL password, and it exists only in a local container.
/// On Azure SQL, SQL authentication is disabled (azureADOnlyAuthentication in Bicep).
/// </remarks>
public sealed class SqlServerFixture : IAsyncLifetime
{
    private MsSqlContainer? _container;

    public static bool Enabled => Environment.GetEnvironmentVariable("SHOPFLOW_RUN_INTEGRATION_TESTS") == "1";

    public string ConnectionString { get; private set; } = string.Empty;

    public IMessagePublisher Publisher { get; } = Substitute.For<IMessagePublisher>();

    public async ValueTask InitializeAsync()
    {
        if (!Enabled)
        {
            return;
        }

        _container = new MsSqlBuilder("mcr.microsoft.com/mssql/server:2022-latest").Build();
        await _container.StartAsync();
        ConnectionString = new Microsoft.Data.SqlClient.SqlConnectionStringBuilder(_container.GetConnectionString())
        {
            InitialCatalog = "sqldb-inventory",
        }.ConnectionString;

        using var provider = BuildServices();
        using var scope = provider.CreateScope();
        await scope.ServiceProvider.GetRequiredService<InventoryDbContext>().Database.MigrateAsync();
    }

    public ServiceProvider BuildServices()
    {
        var configuration = new ConfigurationBuilder()
            .AddInMemoryCollection(new Dictionary<string, string?>
            {
                ["Sql:ConnectionString"] = ConnectionString,
                ["Sql:Outbox:BatchSize"] = "5",
            })
            .Build();

        var services = new ServiceCollection();
        services.AddLogging();
        services.AddSingleton(Publisher);
        services.AddInventoryMessaging();
        services.AddInventoryApplication(configuration);
        services.AddInventoryInfrastructure(configuration, runOutboxPoller: false);
        return services.BuildServiceProvider();
    }

    public async ValueTask DisposeAsync()
    {
        if (_container is not null)
        {
            await _container.DisposeAsync();
        }
    }
}
